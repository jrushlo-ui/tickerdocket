import assert from 'node:assert/strict';
import {describeCoverage,editionOutcome,EXPECTED_SOURCES} from './edition-health.mjs';
import {parseDiscoveryFeed,discoverRegulatoryLeads,reviewedLaunchItems} from './regulatory-discovery.mjs';
import {selectMorningItems} from './morning-brief.mjs';
import {evidenceFetcher} from './source-evidence.mjs';
const at=Date.parse('2026-11-24T22:30:14.716Z');
const rows=EXPECTED_SOURCES.map((source,id)=>({id,source,status:'ok',ended_at:new Date(at-60000).toISOString()}));
assert.equal(describeCoverage(rows,new Date(at).toISOString()).status,'checked');
rows.find(x=>x.source==='Company releases').ended_at=new Date(at+1).toISOString();
assert.equal(describeCoverage(rows,new Date(at).toISOString()).status,'partial');
assert.equal(editionOutcome(0,'checked',1),'verification_pending');
assert.equal(editionOutcome(0,'partial',0),'source_checks_incomplete');
assert.equal(editionOutcome(0,'checked',0),'no_new_verified_items');
const audited=reviewedLaunchItems.filter(x=>x.reviewed_at).map(x=>({...x,impact_evidence_url:x.impact_evidence_url||x.source_url}));
assert.deepEqual(selectMorningItems(audited).map(x=>x.ticker),['COGT','PYPD']);
const feed={name:'Company releases',url:'https://www.globenewswire.com/rss'};
const rss=date=>`<rss><channel><item><title>Example announces FDA acceptance of supplemental application</title><link>https://www.globenewswire.com/news/1</link><pubDate>${date}</pubDate></item></channel></rss>`;
assert.equal(parseDiscoveryFeed(feed,rss(new Date(at-1).toUTCString()),at).length,1);
assert.equal(parseDiscoveryFeed(feed,rss(new Date(at+86400000).toUTCString()),at).length,0);
const entries=Array.from({length:100},(_,i)=>`<entry><title>6-K - Issuer ${i}</title><link href="https://www.sec.gov/Archives/${i}"/><updated>2026-11-24T22:00:00Z</updated></entry>`).join('');
const found=await discoverRegulatoryLeads(at,async url=>new Response(url.includes('browse-edgar')?`<feed>${entries}</feed>`:rss(new Date(at-1).toUTCString())));
assert(found.filter(x=>x.source.startsWith('SEC ')).every(x=>x.coverage_error));
const captured=[];
const DB={prepare(sql){return {bind(...args){this.args=args;return this;},async run(){if(this.args)captured.push(this.args);}};},async batch(statements){return Promise.all(statements.map(s=>s.run()));}};
const archive=evidenceFetcher(new Date(at),async()=>new Response('original body',{status:200}));
const response=await archive.fetch('https://www.fda.gov/feed',{headers:{Authorization:'secret-not-to-store'}});
assert.equal(await response.text(),'original body');
await archive.save(DB);
assert.equal(captured[0][8],'original body');
assert(!JSON.stringify(captured).includes('secret-not-to-store'));
const large=evidenceFetcher(new Date(at),async()=>new Response('x'.repeat(1000001)));
await large.fetch('https://www.fda.gov/large');await large.save(DB);
assert.equal(captured[1][8],null);assert(captured[1][9].includes('exceeded'));
console.log('Passed coverage, future-data isolation, acceptance discovery, SEC saturation and payload-capture regressions.');
